export const getPost = (slug: string) => POSTS.find((p) => p.slug === slug)

// —— 排程發布 —— 以台灣時間為準，未到發佈日（date 在未來）的文章一律隱藏，
// 到當天會透過頁面的 revalidate（每小時）自動出現，不需手動重新部署。
function todayTaipei(): string {
  const tpe = new Date(Date.now() + 8 * 60 * 60 * 1000)
  return tpe.toISOString().slice(0, 10)
}

export function isPublished(post: Post, today: string = todayTaipei()): boolean {
  return post.date <= today
}

// 已發佈（date <= 今天）的文章，依日期新到舊排序
export function getPublishedPosts(): Post[] {
  const today = todayTaipei()
  return POSTS.filter((p) => p.date <= today).sort((a, b) => b.date.localeCompare(a.date))
}
